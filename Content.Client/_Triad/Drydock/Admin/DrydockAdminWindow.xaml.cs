/// <summary>
/// The drydock admin panel: one search box and a row of state chips, and the hull that is
/// selected with everything a decision about it needs. The verbs a hull offers follow its state
/// rather than being greyed in a fixed row, so what is on screen is what will work.
///
/// <para>Every button sends a message and the server pushes the whole state back. Nothing here
/// predicts an outcome, and the server checks each choice again on receipt, so a list that went
/// stale between the state and the click is a refusal rather than a wrong result.</para>
///
/// <para>Strings are built with interpolation, never string.Format, for the same sandbox reason
/// the tamper window records: the multi-arg string.Format overload fails ILVerify in a Release
/// client.</para>
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class DrydockAdminWindow : FancyWindow
{
    private const int PageSize = 50;

    private static readonly Color StoredColor = Color.FromHex("#6ec06e");
    private static readonly Color OutColor = Color.FromHex("#d9a441");
    private static readonly Color HeldColor = Color.FromHex("#cf4f4f");
    private static readonly Color SoldColor = Color.FromHex("#b98ad6");
    private static readonly Color AdminColor = Color.FromHex("#6fa8dc");
    private static readonly Color RefusedColor = Color.FromHex("#ff6a6a");
    private static readonly Color LabelColor = Color.FromHex("#8d8d8d");
    private static readonly StyleBoxFlat SelectedBox = new() { BackgroundColor = Color.FromHex("#3e5e82") };

    /// <summary>
    /// The chips, in the order they are drawn. Null is "All"; the two trailing entries are the
    /// flags the server reads instead of a state name.
    /// </summary>
    private static readonly string?[] Chips =
    {
        null, "Stored", "CheckedOut", "InEscrow",
        "Sold", "Held", "Stranded", "Investigating",
    };

    private readonly DrydockAdminEui _eui;
    private readonly List<Button> _chipButtons = new();

    private DrydockAdminEuiState? _lastState;
    private string? _chip;
    private Guid? _selected;

    public DrydockAdminWindow(DrydockAdminEui eui)
    {
        RobustXamlLoader.Load(this);
        _eui = eui;

        Title = Loc.GetString("drydock-admin-title");

        BuildChips();

        SearchButton.OnPressed += _ => RequestPage(0);
        SearchInput.OnTextEntered += _ => RequestPage(0);
        PrevPageButton.OnPressed += _ => RequestPage(Math.Max(0, (_lastState?.Page ?? 0) - 1));
        NextPageButton.OnPressed += _ => RequestPage(Math.Min(LastPageIndex(), (_lastState?.Page ?? 0) + 1));

        SaveNotesButton.OnPressed += _ => WithSelected(id =>
            _eui.Send(new DrydockAdminNotesMessage { ShipGuid = id, Notes = NotesInput.Text }));
    }

    public void UpdateState(DrydockAdminEuiState state)
    {
        _lastState = state;
        _selected = state.Selected?.Ship.ShipGuid;

        RebuildShipList(state);
        RebuildDetail(state);

        NoticeLabel.Text = state.Notice ?? (state.Selected == null ? Loc.GetString("drydock-admin-no-selection") : string.Empty);
    }

    // ---------------------------------------------------------------- Search and chips

    private void BuildChips()
    {
        for (var i = 0; i < Chips.Length; i++)
        {
            var chip = Chips[i];
            var button = new Button
            {
                Text = Loc.GetString($"drydock-admin-chip-{chip ?? "All"}"),
                StyleClasses = { "ButtonSquare" },
                ToggleMode = true,
                Pressed = chip == null,
                Margin = new Thickness(0, 0, 3, 0),
                HorizontalExpand = true,
            };

            // Stranded is the one chip whose meaning is not its own name.
            if (chip == "Stranded")
                button.ToolTip = Loc.GetString("drydock-admin-chip-Stranded-tooltip");

            button.OnPressed += _ =>
            {
                _chip = chip;
                RequestPage(0);
            };

            _chipButtons.Add(button);
            (i < 4 ? ChipRowTop : ChipRowBottom).AddChild(button);
        }
    }

    private void RequestPage(int page)
    {
        for (var i = 0; i < _chipButtons.Count; i++)
            _chipButtons[i].Pressed = Chips[i] == _chip;

        _eui.Send(new DrydockAdminRequestPageMessage
        {
            Page = page,
            PageSize = PageSize,
            Search = string.IsNullOrWhiteSpace(SearchInput.Text) ? null : SearchInput.Text,
            Chip = _chip,
        });
    }

    private int LastPageIndex()
        => _lastState == null ? 0 : Math.Max(0, (_lastState.TotalShips - 1) / PageSize);

    private string? Reason() => string.IsNullOrWhiteSpace(ReasonInput.Text) ? null : ReasonInput.Text;

    private void WithSelected(Action<Guid> act)
    {
        if (_selected is { } id)
            act(id);
    }

    // ---------------------------------------------------------------- Results

    private void RebuildShipList(DrydockAdminEuiState state)
    {
        var scroll = ShipScroll.GetScrollValue();
        ShipContainer.RemoveAllChildren();

        foreach (var ship in state.Ships)
        {
            var msg = new FormattedMessage();
            msg.PushColor(StateColor(ship.State));
            msg.AddText(ship.Name);
            msg.Pop();

            msg.PushColor(LabelColor);
            msg.AddText($" · {ship.SizeClass ?? "?"} · ");
            msg.AddText(Loc.GetString("drydock-admin-row-owner", ("owner", ship.OwnerName ?? Short(ship.OwnerUserId))));
            msg.Pop();

            msg.AddText("  ");
            msg.PushColor(StateColor(ship.State));
            msg.AddText(RowTag(ship));
            msg.Pop();

            if (ship.BerthId is { } berth)
            {
                msg.PushColor(LabelColor);
                msg.AddText(" · " + Loc.GetString("drydock-admin-row-berth", ("berth", berth)));
                msg.Pop();
            }

            if (ship.Investigating)
            {
                msg.PushColor(HeldColor);
                msg.AddText(" · " + Loc.GetString("drydock-admin-row-investigating"));
                msg.Pop();
            }

            if (ship.LiveThisRound)
            {
                msg.PushColor(OutColor);
                msg.AddText(" · " + Loc.GetString("drydock-admin-row-live"));
                msg.Pop();
            }

            var rich = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(6, 4) };
            rich.SetMessage(msg);

            var highlight = new PanelContainer();
            if (ship.ShipGuid == _selected)
                highlight.PanelOverride = SelectedBox;
            highlight.AddChild(rich);

            var button = new ContainerButton { HorizontalExpand = true };
            button.AddChild(highlight);

            var captured = ship.ShipGuid;
            button.OnPressed += _ => _eui.Send(new DrydockAdminSelectShipMessage { ShipGuid = captured });

            ShipContainer.AddChild(button);
        }

        CountLabel.Text = Loc.GetString("drydock-admin-count", ("shown", state.Ships.Count), ("total", state.TotalShips));

        var totalPages = Math.Max(1, (state.TotalShips + PageSize - 1) / PageSize);
        PageLabel.Text = Loc.GetString("drydock-admin-page", ("page", state.Page + 1), ("pages", totalPages));
        PrevPageButton.Disabled = state.Page <= 0;
        NextPageButton.Disabled = state.Page + 1 >= totalPages;

        ShipScroll.SetScrollValue(scroll);
    }

    /// <summary>The state tag, carrying its own number: the round it went out in, or the time an offer has left.</summary>
    private static string RowTag(DrydockAdminShipDto ship)
    {
        return ship.State switch
        {
            "CheckedOut" => Loc.GetString("drydock-admin-row-out", ("round", ship.CheckedOutRoundId ?? 0)),
            "InEscrow" => Loc.GetString("drydock-admin-row-escrow", ("left", TimeLeft(ship.EscrowExpiresAt))),
            _ => Loc.GetString($"drydock-admin-chip-{ship.State}"),
        };
    }

    /// <summary>Minutes until a deadline, as both sides of an offer read it.</summary>
    private static string TimeLeft(DateTime? expires)
    {
        if (expires is not { } at)
            return Loc.GetString("drydock-admin-expired");

        var left = at - DateTime.UtcNow;
        return left <= TimeSpan.Zero
            ? Loc.GetString("drydock-admin-expired")
            : Loc.GetString("drydock-admin-minutes-left", ("minutes", (int)Math.Ceiling(left.TotalMinutes)));
    }

    // ---------------------------------------------------------------- The selected hull

    private void RebuildDetail(DrydockAdminEuiState state)
    {
        VerbRow.RemoveAllChildren();
        BerthContainer.RemoveAllChildren();
        RevisionContainer.RemoveAllChildren();
        TimelineContainer.RemoveAllChildren();

        var detail = state.Selected;

        SaveNotesButton.Disabled = detail == null;
        GrantBerthButton.Disabled = detail == null;
        EscrowPanel.Visible = detail?.Escrow != null;

        if (detail == null)
        {
            HeaderLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("drydock-admin-no-selection")));
            NotesInput.Text = string.Empty;
            GrantBerthButton.SetItems(Array.Empty<DrydockMenuButton.Item>());
            return;
        }

        var ship = detail.Ship;

        BuildHeader(ship);
        BuildEscrowCard(detail);
        BuildVerbs(state, detail);

        NotesInput.Text = detail.AdminNotes ?? string.Empty;

        BuildGrantMenu(ship.OwnerUserId);
        BuildBerths(state, ship);
        BuildRevisions(detail, ship);
        BuildTimeline(detail);
    }

    private void BuildHeader(DrydockAdminShipDto ship)
    {
        var msg = new FormattedMessage();
        msg.PushColor(StateColor(ship.State));
        msg.AddText(Loc.GetString("drydock-admin-header",
            ("name", ship.Name),
            ("class", ship.SizeClass ?? "?"),
            ("id", Short(ship.ShipGuid)),
            ("revision", ship.CurrentRevision),
            ("owner", ship.OwnerName ?? "?"),
            ("account", Short(ship.OwnerUserId))));
        msg.Pop();

        msg.PushColor(LabelColor);
        msg.AddText(" · " + (ship.BerthId is { } berth
            ? Loc.GetString("drydock-admin-header-berth", ("berth", berth))
            : Loc.GetString("drydock-admin-header-no-berth")));
        msg.AddText(" · " + Loc.GetString("drydock-admin-header-since", ("since", $"{ship.StateChangedAt:yyyy-MM-dd HH:mm}")));
        msg.Pop();

        // The one fact that refuses a restore, so it is never further away than the header.
        if (ship.LiveThisRound)
        {
            msg.PushColor(OutColor);
            msg.AddText(" · " + Loc.GetString("drydock-admin-header-live"));
            msg.Pop();
        }

        HeaderLabel.SetMessage(msg);
    }

    private void BuildEscrowCard(DrydockAdminShipDetailDto detail)
    {
        if (detail.Escrow is not { } escrow)
            return;

        EscrowBodyLabel.Text = Loc.GetString("drydock-admin-escrow-body",
            ("to", escrow.ToName ?? Short(escrow.ToUserId)),
            ("toAccount", Short(escrow.ToUserId)),
            ("from", escrow.FromName ?? Short(escrow.FromUserId)),
            ("made", $"{escrow.CreatedAt:yyyy-MM-dd HH:mm}"),
            ("expires", $"{escrow.ExpiresAt:HH:mm}"),
            ("left", TimeLeft(escrow.ExpiresAt)));

        EscrowLandsLabel.Text = escrow.LandsInBerthId is { } lands
            ? Loc.GetString("drydock-admin-escrow-lands", ("berth", lands))
            : Loc.GetString("drydock-admin-escrow-no-room");
    }

    /// <summary>
    /// The verbs this state actually offers, in the order it offers them: the one that answers
    /// the state comes first. A verb that cannot apply is absent rather than greyed, except where
    /// the reason is worth reading, which is what the menu's detail text is for.
    /// </summary>
    private void BuildVerbs(DrydockAdminEuiState state, DrydockAdminShipDetailDto detail)
    {
        var ship = detail.Ship;

        if (detail.Escrow is { } escrow)
        {
            var cancel = Verb("drydock-admin-cancel-offer", "drydock-admin-cancel-offer-tooltip");
            cancel.OnPressed += _ => _eui.Send(new DrydockAdminCancelOfferMessage { TransferId = escrow.TransferId, Reason = Reason() });
            VerbRow.AddChild(cancel);
        }

        if (ship.State == "Sold" && detail.LastSale is { } sale)
        {
            var restore = Verb("drydock-admin-restore-from-sale", "drydock-admin-restore-from-sale-tooltip");
            restore.OnPressed += _ => OpenRestoreSaleDialog(state, ship, sale);
            VerbRow.AddChild(restore);
        }

        var held = ship.State == "Held";
        var hold = Verb(held ? "drydock-admin-release" : "drydock-admin-hold", "drydock-admin-hold-tooltip");
        hold.OnPressed += _ => _eui.Send(new DrydockAdminHoldMessage { ShipGuid = ship.ShipGuid, Hold = !held, Reason = Reason() });
        VerbRow.AddChild(hold);

        var investigate = Verb(ship.Investigating ? "drydock-admin-close-investigation" : "drydock-admin-investigate",
            "drydock-admin-investigate-tooltip");
        investigate.OnPressed += _ => _eui.Send(new DrydockAdminInvestigateMessage
        {
            ShipGuid = ship.ShipGuid,
            Investigating = !ship.Investigating,
            Reason = Reason(),
        });
        VerbRow.AddChild(investigate);

        // Restore is for a hull that is out, held or sold; a stored one is already home.
        if (ship.State != "Stored" && ship.State != "InEscrow")
        {
            var restoreTo = new DrydockMenuButton
            {
                Text = Loc.GetString("drydock-admin-restore-to"),
                StyleClasses = { "ButtonSquare" },
                Margin = new Thickness(0, 0, 4, 0),
                ToolTip = Loc.GetString("drydock-admin-restore-to-tooltip"),
            };
            restoreTo.SetItems(BerthTargets(state, ship, berthId => _eui.Send(new DrydockAdminRestoreMessage
            {
                ShipGuid = ship.ShipGuid,
                BerthId = berthId,
                Reason = Reason(),
            })));
            VerbRow.AddChild(restoreTo);
        }

        var more = new DrydockMenuButton
        {
            Text = Loc.GetString("drydock-admin-more"),
            StyleClasses = { "ButtonSquare" },
            MinWidth = 34,
            AlignRight = true,
        };
        var extras = new List<DrydockMenuButton.Item>
        {
            new(Loc.GetString("drydock-admin-vacate"), null, ship.BerthId != null,
                () => _eui.Send(new DrydockAdminMoveMessage { ShipGuid = ship.ShipGuid, BerthId = null, Reason = Reason() })),
            new(Loc.GetString("drydock-admin-delete-ship"),
                ship.LiveThisRound ? Loc.GetString("drydock-admin-row-live") : null,
                !ship.LiveThisRound,
                () => _eui.Send(new DrydockAdminDeleteShipMessage { ShipGuid = ship.ShipGuid, Reason = Reason() })),
        };
        more.SetItems(extras);
        VerbRow.AddChild(more);
    }

    private static Button Verb(string label, string tooltip)
    {
        return new Button
        {
            Text = Loc.GetString(label),
            StyleClasses = { "ButtonSquare" },
            Margin = new Thickness(0, 0, 4, 0),
            ToolTip = Loc.GetString(tooltip),
        };
    }

    /// <summary>
    /// The owner's berths as targets for one action. An unusable berth stays listed and names why,
    /// because "there is nowhere to put it" is the answer the admin came for.
    /// </summary>
    private static List<DrydockMenuButton.Item> BerthTargets(DrydockAdminEuiState state, DrydockAdminShipDto ship, Action<int> pick)
    {
        var items = new List<DrydockMenuButton.Item>();

        foreach (var berth in state.OwnerBerths)
        {
            var occupied = berth.OccupantShipGuid != null && berth.OccupantShipGuid != ship.ShipGuid;
            var fits = ClassFits(ship.SizeClass, berth.MaxSizeClass);

            var detail = occupied
                ? Loc.GetString("drydock-admin-berth-occupied")
                : !fits
                    ? Loc.GetString("drydock-admin-berth-too-small")
                    : null;

            var id = berth.BerthId;
            items.Add(new DrydockMenuButton.Item(
                $"#{berth.BerthId} {berth.MaxSizeClass}",
                detail,
                !occupied && fits,
                () => pick(id)));
        }

        return items;
    }

    private void BuildGrantMenu(Guid owner)
    {
        var items = Enum.GetValues<ShipSizeClass>()
            .Select(cls => new DrydockMenuButton.Item(cls.ToString(), null, true,
                () => _eui.Send(new DrydockAdminGrantBerthMessage { OwnerUserId = owner, MaxSizeClass = cls.ToString() })))
            .ToList();

        GrantBerthButton.SetItems(items);
    }

    /// <summary>The owner's berths, drawn by the same row the player's tab uses, so both sides read alike.</summary>
    private void BuildBerths(DrydockAdminEuiState state, DrydockAdminShipDto ship)
    {
        foreach (var berth in state.OwnerBerths)
        {
            // The player's row also draws escrow and a sale price; an admin berth carries neither,
            // so those arrive null and the row simply does not draw them.
            var info = new DrydockBerthInfo(
                berth.BerthId,
                berth.MaxSizeClass,
                sellValue: 0,
                upgradePrice: null,
                upgradeClass: null,
                occupantShipId: berth.OccupantShipGuid,
                occupantName: berth.OccupantName,
                occupantSizeClass: berth.OccupantSizeClass,
                occupantState: berth.OccupantState,
                occupantSellPrice: null,
                occupantTransferId: null,
                occupantOfferedTo: null,
                occupantOfferSecondsLeft: null);

            var row = new DrydockBerthRow(info, canRetrieve: false);

            var empty = berth.OccupantShipGuid == null;
            var fits = ClassFits(ship.SizeClass, berth.MaxSizeClass);
            var id = berth.BerthId;

            var items = new List<DrydockMenuButton.Item>
            {
                new(Loc.GetString("drydock-admin-berth-restore-here"),
                    BerthReason(empty, fits),
                    empty && fits && ship.State != "Stored" && ship.State != "InEscrow",
                    () => _eui.Send(new DrydockAdminRestoreMessage { ShipGuid = ship.ShipGuid, BerthId = id, Reason = Reason() })),
                new(Loc.GetString("drydock-admin-berth-move-here"),
                    BerthReason(empty, fits),
                    empty && fits && ship.State == "Stored",
                    () => _eui.Send(new DrydockAdminMoveMessage { ShipGuid = ship.ShipGuid, BerthId = id, Reason = Reason() })),
                new(Loc.GetString("drydock-admin-berth-delete"),
                    empty ? null : Loc.GetString("drydock-admin-berth-occupied"),
                    empty,
                    () => _eui.Send(new DrydockAdminDeleteBerthMessage { BerthId = id })),
            };
            row.MenuButton.SetItems(items);

            BerthContainer.AddChild(row);
        }
    }

    private static string? BerthReason(bool empty, bool fits)
    {
        if (!empty)
            return Loc.GetString("drydock-admin-berth-occupied");

        return fits ? null : Loc.GetString("drydock-admin-berth-too-small");
    }

    private void BuildRevisions(DrydockAdminShipDetailDto detail, DrydockAdminShipDto ship)
    {
        foreach (var revision in detail.Revisions)
        {
            var msg = new FormattedMessage();
            msg.PushColor(revision.Revision == ship.CurrentRevision ? StoredColor : LabelColor);
            msg.AddText(Loc.GetString("drydock-admin-revision",
                ("revision", revision.Revision),
                ("kind", revision.Kind),
                ("at", $"{revision.CreatedAt:yyyy-MM-dd HH:mm}"),
                ("by", revision.ActorName ?? (revision.ActorUserId is { } a ? Short(a) : "system")),
                ("size", revision.SizeBytes / 1024),
                ("document", Loc.GetString(revision.HasBlob ? "drydock-admin-revision-kept" : "drydock-admin-revision-pruned"))));
            msg.Pop();

            // The appraisal is what a sale would have paid at that revision, so a reversal can be
            // checked against the figure the sale actually used.
            if (revision.AppraisedValue is { } value)
            {
                msg.PushColor(LabelColor);
                msg.AddText(" · " + Loc.GetString("drydock-admin-revision-appraisal", ("value", value)));
                msg.Pop();
            }

            var rich = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(6, 2) };
            rich.SetMessage(msg);

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
            row.AddChild(rich);

            if (revision.HasBlob && revision.Revision != ship.CurrentRevision)
            {
                var promote = new Button { Text = Loc.GetString("drydock-admin-promote"), StyleClasses = { "ButtonSquare" } };
                var captured = revision.Revision;
                promote.OnPressed += _ => _eui.Send(new DrydockAdminPromoteRevisionMessage
                {
                    ShipGuid = ship.ShipGuid,
                    Revision = captured,
                    Reason = Reason(),
                });
                row.AddChild(promote);
            }

            RevisionContainer.AddChild(row);
        }
    }

    /// <summary>
    /// The hull's whole life, actor then subject on every row. A refused-access row is the only
    /// one a console never produces, so it is coloured and carries the tooltip that says so.
    /// </summary>
    private void BuildTimeline(DrydockAdminShipDetailDto detail)
    {
        foreach (var entry in detail.Timeline)
        {
            var refused = entry.Action == "AccessRefused";

            var msg = new FormattedMessage();
            msg.PushColor(LabelColor);
            msg.AddText($"{entry.At:MM-dd HH:mm:ss} ");
            msg.Pop();

            msg.PushColor(refused ? RefusedColor : ActionColor(entry.Action));
            msg.AddText(entry.Action);
            msg.Pop();

            msg.AddText($" {entry.ActorName ?? (entry.ActorUserId is { } a ? Short(a) : "system")}");
            if (entry.SubjectUserId is { } subject)
                msg.AddText($" → {entry.SubjectName ?? Short(subject)}");

            msg.PushColor(LabelColor);
            if (entry.ShipName != null)
                msg.AddText($" · {entry.ShipName}");
            if (entry.BerthId is { } berth)
                msg.AddText($" · #{berth}");
            if (entry.Revision is { } rev)
                msg.AddText($" · r{rev}");
            if (entry.RoundId is { } round)
                msg.AddText($" · round {round}");
            msg.Pop();

            if (!string.IsNullOrEmpty(entry.Reason))
                msg.AddText($" · \"{entry.Reason}\"");

            var rich = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(6, 2) };
            rich.SetMessage(msg);
            if (refused)
                rich.ToolTip = Loc.GetString("drydock-admin-refused-tooltip");

            TimelineContainer.AddChild(rich);
        }
    }

    private void OpenRestoreSaleDialog(DrydockAdminEuiState state, DrydockAdminShipDto ship, DrydockAdminSaleDto sale)
    {
        // The berth the ship last sat in, when the owner still has it free and it still fits.
        var targets = state.OwnerBerths
            .Where(b => b.OccupantShipGuid == null && ClassFits(ship.SizeClass, b.MaxSizeClass))
            .Select(b => b.BerthId)
            .ToList();

        var dialog = new DrydockRestoreSaleDialog(ship, sale, targets, ship.LastBerthId, (berthId, takeMoney, reason) =>
            _eui.Send(new DrydockAdminRestoreFromSaleMessage
            {
                ShipGuid = ship.ShipGuid,
                BerthId = berthId,
                TakeMoneyBack = takeMoney,
                Reason = reason,
            }));

        dialog.OpenCentered();
    }

    // ---------------------------------------------------------------- Shared reads

    /// <summary>
    /// The same rule the player's tab applies: a berth holds its class or smaller, and text that
    /// parses as neither is "does not fit" rather than a crash. The server checks it again.
    /// </summary>
    private static bool ClassFits(string? shipClass, string berthClass)
    {
        return Enum.TryParse<ShipSizeClass>(shipClass, out var ship)
            && Enum.TryParse<ShipSizeClass>(berthClass, out var berth)
            && berth >= ship;
    }

    private static string Short(Guid id) => id.ToString("N")[..8];

    private static Color StateColor(string state) => state switch
    {
        "Stored" => StoredColor,
        "CheckedOut" => OutColor,
        "InEscrow" => OutColor,
        "Sold" => SoldColor,
        "Held" => HeldColor,
        _ => Color.Gray,
    };

    private static Color ActionColor(string action) => action switch
    {
        "Store" or "Retrieve" => StoredColor,
        "Fallback" => OutColor,
        _ => AdminColor,
    };
}
