    /// <summary>
    /// The same rule the player's console applies: a berth holds its class or smaller, and text
    /// that parses as neither is "does not fit" rather than a crash. The server checks it again.
    /// </summary>
    private static bool ClassFits(string? shipClass, string berthClass)
    {
        return Enum.TryParse<ShipSizeClass>(shipClass, out var ship)
            && Enum.TryParse<ShipSizeClass>(berthClass, out var berth)
            && berth >= ship;
    }

    private static string Short(Guid id) => id.ToString("N")[..8];
