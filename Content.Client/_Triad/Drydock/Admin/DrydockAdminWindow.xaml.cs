    /// <summary>The owner's berths, drawn by the same row the player's console uses, so both sides read alike.</summary>
    private void BuildBerths(DrydockAdminEuiState state, DrydockAdminShipDto ship)
    {
        var free = state.OwnerBerths.Count(b => b.OccupantShipGuid == null);
        BerthsTitle.Text = Loc.GetString("drydock-admin-berths-title", ("owner", ship.OwnerName ?? Short(ship.OwnerUserId)));
        BerthsCount.Text = Loc.GetString("drydock-admin-berths-count", ("free", free), ("total", state.OwnerBerths.Count));

        foreach (var berth in state.OwnerBerths)
        {
            // The player's row also draws escrow and a sale price; an admin berth carries neither,
            // so those arrive null and the row simply does not draw them.
            var info = new DrydockBerthInfo(
                berth.BerthId,
                berth.MaxSizeClass,
                sellValue: 0,
                upgradePrice: null,
                upgradeClass: null,
                occupantShipId: berth.OccupantShipGuid,
                occupantName: berth.OccupantName,
                occupantSizeClass: berth.OccupantSizeClass,
                occupantState: berth.OccupantState,
                occupantSellPrice: null,
                occupantTransferId: null,
                occupantOfferedTo: null,
                occupantOfferSecondsLeft: null);

            var row = new DrydockBerthRow(info, canRetrieve: false) { Margin = new Thickness(0, 0, 0, 3) };

            var empty = berth.OccupantShipGuid == null;
            var fits = ClassFits(ship.SizeClass, berth.MaxSizeClass);
            var id = berth.BerthId;

            row.MenuButton.SetItems(new List<DrydockMenuButton.Item>
            {
                new(Loc.GetString("drydock-admin-berth-restore-here"),
                    BerthReason(empty, fits),
                    empty && fits && ship.State is not ("Stored" or "InEscrow" or "Sold"),
                    () => _eui.Send(new DrydockAdminRestoreMessage { ShipGuid = ship.ShipGuid, BerthId = id, Reason = Reason() })),
                new(Loc.GetString("drydock-admin-berth-move-here"),
                    BerthReason(empty, fits),
                    empty && fits && ship.State == "Stored",
                    () => _eui.Send(new DrydockAdminMoveMessage { ShipGuid = ship.ShipGuid, BerthId = id, Reason = Reason() })),
                new(Loc.GetString("drydock-admin-berth-delete"),
                    empty ? null : Loc.GetString("drydock-admin-berth-occupied"),
                    empty,
                    () => _eui.Send(new DrydockAdminDeleteBerthMessage { BerthId = id })),
            });

            BerthContainer.AddChild(row);
        }
    }

    private static string? BerthReason(bool empty, bool fits)
    {
        if (!empty)
            return Loc.GetString("drydock-admin-berth-occupied");

        return fits ? null : Loc.GetString("drydock-admin-berth-too-small");
    }

    /// <summary>
    /// The hull's whole life: a fixed timestamp column, then what happened, actor before subject.
    /// A refused-access row is the only one a console never produces, so it is coloured and says
    /// so on hover.
    /// </summary>
    private void BuildTimeline(DrydockAdminShipDetailDto detail)
    {
        foreach (var entry in detail.Timeline)
        {
            var refused = entry.Action == "AccessRefused";

            var when = new Label
            {
                Text = $"{entry.At:MM-dd HH:mm}",
                FontOverride = _small,
                Modulate = Dim,
                MinWidth = 110,
                VerticalAlignment = VAlignment.Top,
            };

            var msg = new FormattedMessage();
            msg.PushColor(refused ? Sold : Color.White);
            msg.AddText(Loc.GetString($"drydock-admin-action-{entry.Action}"));
            msg.Pop();

            msg.AddText($" {entry.ActorName ?? (entry.ActorUserId is { } a ? Short(a) : "system")}");
            if (entry.SubjectUserId is { } subject && entry.SubjectUserId != entry.ActorUserId)
                msg.AddText($" → {entry.SubjectName ?? Short(subject)}");

            msg.PushColor(Key);
            if (entry.BerthId is { } berth)
                msg.AddText($" · #{berth}");
            if (entry.Revision is { } rev)
                msg.AddText($" · r{rev}");
            if (entry.RoundId is { } round)
                msg.AddText($" · round {round}");
            if (!string.IsNullOrEmpty(entry.Reason))
                msg.AddText($" · {entry.Reason}");
            msg.Pop();

            var what = new RichTextLabel { HorizontalExpand = true };
            what.SetMessage(msg);

            var line = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 4),
            };
            line.AddChild(when);
            line.AddChild(what);

            var rule = new PanelContainer { PanelOverride = TimelineRule(), HorizontalExpand = true };
            rule.AddChild(line);
            if (refused)
                rule.ToolTip = Loc.GetString("drydock-admin-refused-tooltip");

            TimelineContainer.AddChild(rule);
        }
    }

    /// <summary>
    /// The fee is quoted against the current revision's appraisal, which is the figure the server
    /// charges against for a berthed hull; the dialog says when the hull is live and will be
    /// appraised again. The dialog's own reason is what the owner reads, and the panel's inline
    /// reason box stands in when it is left empty.
    /// </summary>
    private void OpenImpoundDialog(DrydockAdminShipDetailDto detail)
    {
        var ship = detail.Ship;
        var appraisal = detail.Revisions.FirstOrDefault(r => r.Revision == ship.CurrentRevision)?.AppraisedValue;

        var dialog = new DrydockImpoundDialog(ship, appraisal, _lastState?.ImpoundDefaultPercent ?? 50, (percent, redeemable, reason) =>
            _eui.Send(new DrydockAdminImpoundMessage
            {
                ShipGuid = ship.ShipGuid,
                FeePercent = percent,
                Redeemable = redeemable,
                Reason = reason ?? Reason(),
            }));

        dialog.OpenCentered();
    }

    private void OpenRestoreSaleDialog(DrydockAdminEuiState state, DrydockAdminShipDto ship, DrydockAdminSaleDto sale)
    {
        var targets = state.OwnerBerths
            .Where(b => b.OccupantShipGuid == null && ClassFits(ship.SizeClass, b.MaxSizeClass))
            .Select(b => b.BerthId)
            .ToList();

        var dialog = new DrydockRestoreSaleDialog(ship, sale, targets, ship.LastBerthId, (berthId, takeMoney, reason) =>
            _eui.Send(new DrydockAdminRestoreFromSaleMessage
            {
                ShipGuid = ship.ShipGuid,
                BerthId = berthId,
                TakeMoneyBack = takeMoney,
                Reason = reason,
            }));

        dialog.OpenCentered();
    }

