// Triad: drydock tab.
using Content.Shared._NF.Bank;
using Content.Shared._NF.Shipyard.BUI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NF.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class DrydockBerthRow : PanelContainer
{
    public int BerthId;

    public DrydockBerthRow(DrydockBerthInfo berth)
    {
        RobustXamlLoader.Load(this);

        BerthId = berth.BerthId;
        BerthLabel.Text = $"#{berth.BerthId} {berth.MaxSizeClass}";
        OccupantLabel.Text = berth.OccupantName != null
            ? Loc.GetString("shipyard-console-berth-holds", ("ship", berth.OccupantName))
            : Loc.GetString("shipyard-console-berth-empty");

        // A berth with a ship in it neither sells nor upgrades from here: the ship would have to
        // move first, and the server refuses both anyway. The buttons say so by being disabled
        // rather than by vanishing, so the layout does not jump.
        var occupied = berth.OccupantShipId != null;

        if (berth.UpgradePrice is { } price && berth.UpgradeClass != null)
        {
            UpgradeButton.Text = Loc.GetString("shipyard-console-berth-upgrade-button",
                ("class", berth.UpgradeClass), ("price", BankSystemExtensions.ToSpesoString(price)));
            UpgradeButton.Disabled = occupied;
        }
        else
        {
            UpgradeButton.Visible = false;
        }

        SellButton.Text = $"{Loc.GetString("shipyard-console-berth-sell-button")} (+{BankSystemExtensions.ToSpesoString(berth.SellValue)})";
        SellButton.Disabled = occupied;
    }
}
