    /// <summary>
    /// Triad: the picker for Transfer…, filled from the captains the last state listed, greyed
    /// when none of their free berths would take the ship.
    /// </summary>
    private void OpenTransferPicker(Guid shipId, string shipName, string? shipClass)
    {
        var items = _lastCaptains
            .OrderBy(c => c.Name, StringComparer.CurrentCultureIgnoreCase)
            .Select(captain =>
            {
                var fits = captain.FreeBerthClasses.Any(berthClass => ClassFits(shipClass, berthClass));
                var recipient = captain.UserId;
                return new DrydockListPicker.Item(
                    captain.Name,
                    fits ? string.Join(", ", captain.FreeBerthClasses.Distinct()) : Loc.GetString("shipyard-console-transfer-picker-no-berth"),
                    fits,
                    () => OnOfferTransfer?.Invoke(shipId, recipient));
            })
            .ToList();

        new DrydockListPicker(
            Loc.GetString("shipyard-console-transfer-picker-title", ("ship", shipName)),
            Loc.GetString("shipyard-console-transfer-picker-hint"),
            Loc.GetString("shipyard-console-transfer-picker-empty"),
            items).OpenCentered();
    }

    /// <summary>Triad: the picker for Move…, listing the operator's other empty berths the ship fits.</summary>
    private void OpenMovePicker(Guid shipId, string shipName, List<DrydockBerthInfo> targets)
