    /// <summary>
    /// Triad: the offer clocks tick here, once a second, from the last state the server sent. A
    /// clock that reaches zero stays at zero until the next state says the offer is gone.
    /// </summary>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _sinceState += args.DeltaSeconds;

        // Every frame, not once a second: this is the only thing moving while the server is busy,
        // so it has to look alive.
        if (_storingFor >= 0f)
        {
            _storingFor += args.DeltaSeconds;
            if (_storingFor >= StoreFeedbackTimeout)
            {
                // The server never answered. Give the button back rather than stranding the
                // operator at a console that looks permanently busy.
                _storingFor = -1f;
                PopulateDeedShip(_lastDeedShip);
            }
            else
            {
                var dots = new string('.', (int)(_storingFor * 2) % 4);
                StoreButton.Text = Loc.GetString("shipyard-console-storing-button") + dots;
            }
        }

        if (_retrievingFor >= 0f)
        {
            _retrievingFor += args.DeltaSeconds;
            if (_retrievingFor >= StoreFeedbackTimeout)
            {
                // The server never answered; redraw the rows as the last state had them.
                _retrievingFor = -1f;
                _retrievingRow = null;
                _escrowRows.Clear();
                PopulateBerths(_lastBerths, _lastCanRetrieve);
            }
            else if (_retrievingRow != null)
            {
                var dots = new string('.', (int)(_retrievingFor * 2) % 4);
                _retrievingRow.RetrieveButton.Text = Loc.GetString("shipyard-console-retrieving-button") + dots;
            }
        }

        var elapsed = (int)_sinceState;
        if (elapsed == _lastElapsed)
            return;

        _lastElapsed = elapsed;
        foreach (var (label, seconds) in _offerClocks)
            label.Text = DrydockText.Left(seconds - elapsed);
        foreach (var (row, seconds) in _escrowRows)
            row.SetTimeLeft(seconds - elapsed);
    }

