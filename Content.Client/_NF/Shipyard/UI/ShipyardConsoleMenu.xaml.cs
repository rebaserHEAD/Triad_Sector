            typed => OnSellStoredShip?.Invoke(shipId, typed.Trim())).OpenCentered();
    }

    /// <summary>
    /// Triad: the same rule the server applies to a stored ship's new name, so the button greys
    /// on the same input the server would refuse. Thirty characters is the deed's own limit.
    /// </summary>
    private static bool IsValidStoredShipName(string name)
    {
        name = name.Trim();
        if (name.Length == 0 || name.Length > 30)
            return false;

        foreach (var c in name)
        {
            if (!char.IsAsciiLetterOrDigit(c) && c != ' ' && c != '-')
                return false;
        }

        return true;
    }

    /// <summary>
    /// Triad: the same ladder the server's berth check walks: a berth takes any hull of its class
    /// or smaller. Unparseable text on either side is "does not fit", never a crash.
    /// </summary>
    private static bool ClassFits(string? shipClass, string berthClass)
    {
        return Enum.TryParse<ShipSizeClass>(shipClass, out var ship)
            && Enum.TryParse<ShipSizeClass>(berthClass, out var berth)
            && berth >= ship;
    }

    /// <summary>
    /// Triad: one alert per offer addressed to the operator, drawn as a line in the escrow amber:
    /// who offers what and where it lands, the clock, Accept, Decline. The last-berth warning
    /// sits under the first line whenever taking the ship would leave one of the operator's own
    /// with nowhere to dock; Accept is disabled outright when no free berth fits.
    /// </summary>
    private void PopulateOffers()
    {
        Offers.RemoveAllChildren();

        foreach (var offer in _lastOffers)
        {
            var panel = new PanelContainer
            {
                Margin = new Thickness(0, 0, 0, 10),
                PanelOverride = new StyleBoxFlat
                {
                    BorderThickness = new Thickness(2),
                    BorderColor = DrydockText.AmberBorder,
                    BackgroundColor = DrydockText.AmberFill,
                },
            };
            var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(10, 6), VerticalAlignment = VAlignment.Center };
            panel.AddChild(line);

            var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
            var headline = new FormattedMessage();
            headline.AddBold(offer.OfferedBy);
            headline.AddColored(" " + Loc.GetString("shipyard-console-transfer-offers") + " ", DrydockText.Dim);
            headline.AddBold(offer.ShipName);
            headline.AddColored(" " + (offer.LandsInBerthId is { } berth
                ? Loc.GetString("shipyard-console-transfer-into", ("class", DrydockText.Class(offer.SizeClass)), ("berth", berth))
                : Loc.GetString("shipyard-console-transfer-no-room", ("class", DrydockText.Class(offer.SizeClass)))), DrydockText.Dim);
            var headlineLabel = new RichTextLabel();
            headlineLabel.SetMessage(headline);
            text.AddChild(headlineLabel);

            if (offer.LandsInBerthId != null && WouldLeaveAShipWithoutABerth(consumes: 1))
            {
                var stranded = _lastDeedShip?.Name
                    ?? _lastShips.FirstOrDefault(s => s.State == "CheckedOut")?.Name
                    ?? Loc.GetString("shipyard-console-transfer-your-ship");
                text.AddChild(new Label
                {
                    Text = Loc.GetString("shipyard-console-transfer-warning", ("ship", stranded)),
                    Modulate = DrydockText.Warning,
                });
            }
            line.AddChild(text);

            var clock = new Label { Text = DrydockText.Left(offer.SecondsLeft), Modulate = DrydockText.Dim, Margin = new Thickness(12, 0) };
            line.AddChild(clock);
            _offerClocks.Add((clock, offer.SecondsLeft));

            var accept = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-accept-button"),
                StyleClasses = { "ButtonSquare", StyleNano.ButtonPrimary },
                MinWidth = 84,
                Disabled = !_validId || offer.LandsInBerthId == null,
            };
            var decline = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-decline-button"),
                StyleClasses = { "ButtonSquare" },
                MinWidth = 84,
                Margin = new Thickness(8, 0, 0, 0),
                Disabled = !_validId,
            };
            line.AddChild(accept);
            line.AddChild(decline);

            var transferId = offer.TransferId;
            accept.OnPressed += _ => OnAcceptTransfer?.Invoke(transferId);
            decline.OnPressed += _ => OnDeclineTransfer?.Invoke(transferId);

            Offers.AddChild(panel);
        }
    }
