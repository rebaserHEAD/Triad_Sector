    private bool WouldLeaveAShipWithoutABerth(int consumes)
    {
        var free = _lastBerths.Count(b => b.OccupantShipId == null);
        var shipsOut = _lastShips.Count(s => s.State == "CheckedOut");
        return shipsOut > 0 && free - consumes < shipsOut;
    }


