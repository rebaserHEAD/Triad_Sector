    public void UpdateState(ShipyardConsoleInterfaceState state)
    {
        BalanceLabel.Text = BankSystemExtensions.ToSpesoString(state.Balance);
        var shipPrice = 0;
        if (!state.FreeListings)
            shipPrice = state.ShipSellValue;

        ShipAppraisalLabel.Text = $"{BankSystemExtensions.ToSpesoString(shipPrice)} ({state.SellRate * 100.0f:F1}%)";
        SellShipButton.Disabled = state.ShipDeedTitle == null;
        UnassignDeedButton.Disabled = state.ShipDeedTitle == null;

        // Show/hide and enable/disable rename controls based on whether there's a ship deed
        var hasShipDeed = state.ShipDeedTitle != null;
        RenameContainer.Visible = hasShipDeed;
        RenameLineEdit.Editable = hasShipDeed;
        RenameButton.Disabled = !hasShipDeed;

        SaveShipButton.Disabled = !state.IsTargetIdPresent;
        LoadShipButton.Disabled = !state.IsTargetIdPresent;
        LoadShipButton.ToolTip = state.IsTargetIdPresent
            ? null
            : Loc.GetString("shipyard-console-load-ship-no-id");
        TargetIdButton.Text = state.IsTargetIdPresent
            ? Loc.GetString("id-card-console-window-eject-button")
            : Loc.GetString("id-card-console-window-insert-button");
        if (state.ShipDeedTitle != null)
        {
            DeedTitle.Text = state.ShipDeedTitle;
        }
        else
        {
            DeedTitle.Text = $"None";
        }
        _freeListings = state.FreeListings;
        _validId = state.IsTargetIdPresent;
        PopulateProducts(_lastAvailableProtos, _lastUnavailableProtos, _freeListings, _validId);

        // Triad: drydock tab. Hidden outright when the master switch is off, rather than shown with
        // buttons that would every one of them come back refused.
        Tabs.SetTabVisible(1, state.DrydockEnabled);

        // The lockout: someone else's registered card in the slot. Decided here because one console
        // state is shared by every viewer and only the client knows which viewer it is.
        LockoutPanel.Visible = LocalUserId != null && state.DeedOwnerUserId is { } deedOwner && deedOwner != LocalUserId;

        _lastShips = state.StoredShips;
        _lastBerths = state.Berths;
        _lastCaptains = state.Captains;
        _armedOffer = null;
        _sinceState = 0f;
        _lastElapsed = -1;
        _offerClocks.Clear();
        _escrowRows.Clear();
        PopulateDeedShip(state.DeedShip);
        PopulateOffers(state.TransferOffers);
        PopulateBerths(state.Berths, canRetrieve: state.IsTargetIdPresent && state.ShipDeedTitle == null);
        PopulateBuyMenu(state.BerthPrices);

        var free = state.Berths.Count(b => b.OccupantShipId == null);
        BerthSummaryLabel.Text = Loc.GetString("shipyard-console-berths-free", ("free", free), ("total", state.Berths.Count));
    }

    /// <summary>
    /// Triad: the card at the top. Store lands in the server's preferred berth; the arrow beside it
    /// lists the other free berths the hull fits. With nothing that fits, Store says so and stays
    /// disabled rather than sending a request the server would refuse.
    /// </summary>
    private void PopulateDeedShip(DrydockDeedShipInfo? ship)
    {
        DeedShipPanel.Visible = ship != null;
        _defaultBerth = ship?.DefaultBerthId;
        if (ship == null)
            return;

        DeedShipLabel.Text = ship.MinutesOut is { } minutes
            ? Loc.GetString("shipyard-console-deed-ship-out", ("ship", ship.Name), ("class", ship.SizeClass ?? "?"), ("minutes", minutes))
            : Loc.GetString("shipyard-console-deed-ship-new", ("ship", ship.Name), ("class", ship.SizeClass ?? "?"));

        StoreButton.Text = ship.DefaultBerthId is { } berth
            ? Loc.GetString("shipyard-console-store-in-button", ("berth", berth))
            : Loc.GetString("shipyard-console-store-no-fit-button");
        StoreButton.Disabled = ship.DefaultBerthId == null || !_validId;

        StoreMenuButton.SetItems(ship.FittingBerthIds
            .Where(id => id != ship.DefaultBerthId)
            .Select(id => new DrydockMenuButton.Item(
                Loc.GetString("shipyard-console-store-in-button", ("berth", id)),
                _lastBerths.FirstOrDefault(b => b.BerthId == id)?.MaxSizeClass,
                _validId,
                () => OnStore?.Invoke(id))));
    }

    /// <summary>
    /// Triad: one row per berth. Retrieve is the row's one button, shown only when it would work;
    /// the rarer verbs sit in the row's menu, with a disabled entry saying why.
    /// </summary>
    private void PopulateBerths(List<DrydockBerthInfo> berths, bool canRetrieve)
    {
        Berths.RemoveAllChildren();

        foreach (var berth in berths)
        {
            var row = new DrydockBerthRow(berth, canRetrieve);
            row.RetrieveButton.OnPressed += _ =>
            {
                if (row.OccupantShipId is { } shipId)
                    OnRetrieve?.Invoke(shipId);
            };

            if (berth.OccupantTransferId is { } transferId)
            {
                row.CancelButton.Disabled = !_validId;
                row.CancelButton.OnPressed += _ => OnCancelTransfer?.Invoke(transferId);
                _escrowRows.Add((row, berth.OccupantOfferSecondsLeft ?? 0));
            }

            var items = new List<DrydockMenuButton.Item>();
            var occupied = berth.OccupantShipId != null;

            if (berth.OccupantShipId is { } occupant && berth.OccupantState == "Stored")
            {
                var shipName = berth.OccupantName ?? "?";
                var shipClass = berth.OccupantSizeClass;
                var fromBerth = berth.BerthId;
                var elsewhere = berths.Where(b => b.BerthId != fromBerth && b.OccupantShipId == null && ClassFits(shipClass, b.MaxSizeClass)).ToList();

                items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-rename"), null, _validId,
                    () => OpenRenamePrompt(occupant, shipName)));
                items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-move"),
                    elsewhere.Count == 0 ? Loc.GetString("shipyard-console-menu-nowhere") : null, _validId && elsewhere.Count > 0,
                    () => OpenMovePicker(occupant, shipName, elsewhere)));
                items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-transfer"), null, _validId,
                    () => OpenTransferPicker(occupant, shipName, shipClass)));
                items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-sell"),
                    berth.OccupantSellPrice is { } sellPrice ? BankSystemExtensions.ToSpesoString(sellPrice) : Loc.GetString("shipyard-console-menu-no-appraisal"),
                    _validId && berth.OccupantSellPrice != null,
                    () => OpenSellPrompt(occupant, shipName, berth.OccupantSellPrice ?? 0)));
            }

            if (berth.UpgradePrice is { } price && berth.UpgradeClass != null)
            {
                items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-upgrade-berth"),
                    $"{berth.UpgradeClass} {BankSystemExtensions.ToSpesoString(price)}", _validId,
                    () => OnUpgradeBerth?.Invoke(row.BerthId)));
            }

            items.Add(new DrydockMenuButton.Item(Loc.GetString("shipyard-console-menu-sell-berth"),
                occupied ? Loc.GetString("shipyard-console-menu-occupied") : $"+{BankSystemExtensions.ToSpesoString(berth.SellValue)}",
                !occupied && _validId,
                () => OnSellBerth?.Invoke(row.BerthId)));

            row.MenuButton.SetItems(items);
            Berths.AddChild(row);
        }
    }

