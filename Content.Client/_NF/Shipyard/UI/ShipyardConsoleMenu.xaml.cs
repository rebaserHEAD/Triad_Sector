    /// <summary>
    /// Triad: the same rule the server applies to a stored ship's new name, so the button greys
    /// on the same input the server would refuse. Thirty characters is the deed's own limit.
    /// </summary>
    private static bool IsValidStoredShipName(string name)
    {
        name = name.Trim();
        if (name.Length == 0 || name.Length > 30)
            return false;

        foreach (var c in name)
        {
            if (!char.IsAsciiLetterOrDigit(c) && c != ' ' && c != '-')
                return false;
        }

        return true;
    }

    /// <summary>
    /// Triad: the same ladder the server's berth check walks: a berth takes any hull of its class
    /// or smaller. Unparseable text on either side is "does not fit", never a crash.
    /// </summary>
    private static bool ClassFits(string? shipClass, string berthClass)
    {
        return Enum.TryParse<ShipSizeClass>(shipClass, out var ship)
            && Enum.TryParse<ShipSizeClass>(berthClass, out var berth)
            && berth >= ship;
    }

    /// <summary>
    /// Triad: one alert per offer addressed to the operator. Accept is disabled outright when no
    /// free berth fits; the last-berth warning is armed by the first press of Accept and never
    /// shown pre-emptively, and a fresh state disarms it again.
    /// </summary>
    private void PopulateOffers(List<DrydockTransferOfferInfo> offers)
    {
        Offers.RemoveAllChildren();

        foreach (var offer in offers)
        {
            // Never an alert for one's own offer; the escrow row already says it.
            if (LocalUserId != null && offer.OfferedByUserId == LocalUserId)
                continue;

            var panel = new PanelContainer
            {
                Margin = new Thickness(0, 8, 0, 6),
                PanelOverride = new StyleBoxFlat
                {
                    BorderThickness = new Thickness(2),
                    BorderColor = Color.FromHex("#3e5e82"),
                    BackgroundColor = Color.FromHex("#1a2430"),
                },
            };
            var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(6, 4) };
            panel.AddChild(body);

            body.AddChild(new Label
            {
                Text = Loc.GetString("shipyard-console-transfer-offer",
                    ("owner", offer.OfferedBy), ("ship", offer.ShipName), ("class", offer.SizeClass ?? "?")),
            });

            var prefix = offer.LandsInBerthId is { } berth
                ? Loc.GetString("shipyard-console-transfer-lands-in", ("berth", berth))
                : Loc.GetString("shipyard-console-transfer-no-room");
            var clock = new Label { Text = $"{prefix} · {DrydockClock.Left(offer.SecondsLeft)}", Modulate = Color.FromHex("#999999") };
            body.AddChild(clock);
            _offerClocks.Add((clock, prefix, offer.SecondsLeft));

            var warning = new Label
            {
                Text = Loc.GetString("shipyard-console-transfer-warning"),
                Modulate = Color.FromHex("#d9a441"),
                Visible = false,
            };
            body.AddChild(warning);

            var buttons = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 4, 0, 0) };
            var accept = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-accept-button"),
                StyleClasses = { "ButtonSquare" },
                MinWidth = 120,
                Disabled = !_validId || offer.LandsInBerthId == null,
            };
            var decline = new Button
            {
                Text = Loc.GetString("shipyard-console-transfer-decline-button"),
                StyleClasses = { "ButtonSquare", "ButtonCaution" },
                MinWidth = 100,
                Margin = new Thickness(4, 0, 0, 0),
                Disabled = !_validId,
            };
            buttons.AddChild(accept);
            buttons.AddChild(decline);
            body.AddChild(buttons);

            var transferId = offer.TransferId;
            accept.OnPressed += _ =>
            {
                if (_armedOffer != transferId && WouldLeaveAShipWithoutABerth(consumes: 1))
                {
                    _armedOffer = transferId;
                    warning.Visible = true;
                    accept.Text = Loc.GetString("shipyard-console-transfer-confirm-button");
                    return;
                }

                OnAcceptTransfer?.Invoke(transferId);
            };
            decline.OnPressed += _ => OnDeclineTransfer?.Invoke(transferId);

            Offers.AddChild(panel);
        }
    }
